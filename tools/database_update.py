def generate_dataset_update_sql(start_id, end_id, dataset_lines):
    """
    生成PostgreSQL的UPDATE语句，批量修改指定ID范围的多个字段
    字段顺序：data_path, convert_path, convert_test_status, convert_test_version,
              convert_status, convert_version_ps, convert_version, total_episodes,
              converted_episodes, skipped_episodes
    """
    total_needed = end_id - start_id + 1
    if len(dataset_lines) < total_needed:
        print(f"警告：数据列表长度({len(dataset_lines)})小于需要的数量({total_needed})，剩余ID用默认值填充")
    
    # 定义字段名列表（与每行数据的列对应）
    fields = [
        'motion_annotation_status','motion_annotation_version_ps'
    ]
    
    # 为每个字段生成CASE语句块
    case_blocks = {}
    for field in fields:
        case_blocks[field] = []
    
    for idx, current_id in enumerate(range(start_id, end_id + 1)):
        # 获取对应行数据，超出范围用默认值
        if idx < len(dataset_lines):
            # 按制表符拆分每行数据（处理空值）
            line_data = dataset_lines[idx].strip().split('\t')
            # 补全不足的列（用空字符串填充）
            while len(line_data) < len(fields):
                line_data.append('')
        else:
            # 默认值
            line_data = ['default_value'] * len(fields)
        
        # 为每个字段生成WHEN语句
        for field_idx, field in enumerate(fields):
            value = line_data[field_idx].strip() if line_data[field_idx].strip() else 'NULL'
            # 转义单引号（字符串值需要加引号，数字/NULL不需要）
            if value != 'NULL' and not value.replace('.', '').replace('-', '').isdigit():
                value_escaped = value.replace("'", "''")
                case_blocks[field].append(f"    WHEN {current_id} THEN '{value_escaped}'")
            else:
                case_blocks[field].append(f"    WHEN {current_id} THEN {value}")
    
    # 组装每个字段的SET语句
    set_clauses = []
    for field in fields:
        case_lines = '\n'.join(case_blocks[field])
        # ELSE保持原字段值不变
        set_clauses.append(f"{field} = CASE id\n{case_lines}\n    ELSE {field}\nEND")
    
    # 组装最终SQL
    set_block = ",\n".join(set_clauses)
    sql = f"""UPDATE datasets
SET {set_block}
WHERE id BETWEEN {start_id} AND {end_id};"""

    return sql

